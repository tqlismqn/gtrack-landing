/* ============================================================================
   CTA-VARIANT — выбор надписи кнопки «попробовать» под ступень ширины.

   Почему функция, а не медиазапрос. Раньше ступень диктовала ИМЯ варианта:
   ниже m показывался ctaShort, ниже 400 — ctaTiny. Но «короткий» вариант
   короче полного только в русском, чешском, испанском и румынском: в восьми
   локалях из двенадцати он не короче, а в пяти (en, it, uk, fr, lv) — строго
   длиннее. Полоса 401–430 попадала только под правило «короткий» и получала
   надпись ДЛИННЕЕ полной — отсюда и рвущаяся шапка, и неработающий своп.

   Правило теперь такое: ступень задаёт, сколько вариантов ДОСТУПНО, а функция
   берёт из доступных самый короткий. Тексты локалей при этом не трогаются —
   редактурой 12 файлов это не чинится, при следующем переводе всё вернётся.

   Считается по строке, а не по пикселям: функция работает на сервере, где
   ширины текста нет. Ничья решается в пользу более полного варианта.

   🔴 ЦЕНА ЭТОГО ПРОКСИ ИЗМЕРЕНА — не досочиняй её, перемеряй.
   Замер 17.08 (прод-сборка, Chromium, Onest 600/14): порядок по символам
   совпадает с порядком по пикселям не везде. На ступени `narrow` (320–430) —
   той самой, где шапка и рвалась, — выбранный вариант совпадает с пиксельным
   минимумом во всех 12 локалях, отклонение 0 px. На ступени `mid` промах есть
   в трёх: de +4,2 px, pl +4,2 px (ничьи по символам, решены в пользу полного)
   и it +0,7 px — настоящий разворот, 15 символов оказались шире 16.
   Максимум ошибки прокси: **4,2 px**.

   Прокси законен ровно пока у шапки есть запас. В самой тесной точке ступени
   `mid` — вьюпорт 431 px, худшая по пикселям надпись `uk` (169 px) — запас
   до отказа (бургер за краем либо вордмарк из рамки лого) равен **48 px**,
   это ×11 от ошибки прокси. Добавишь в шапку ещё один элемент — ЗАПАС
   ПЕРЕМЕРИТЬ: когда он съеден, «по длине строки» перестаёт быть безопасным
   и выбор придётся вести по настоящей ширине текста.
   ============================================================================ */

/** Ступень ширины окна. Числа порогов живут в `@theme` (globals.css) и
 *  применяются медиазапросами в стилях шапки; здесь их намеренно нет.
 *  - `wide`   — от ступени `m` и шире: места хватает на полный текст;
 *  - `mid`    — уже `m`, но шире `s`;
 *  - `narrow` — ступень `s` и уже (полоса 320–430, включая 401–430). */
export type CtaStep = "wide" | "mid" | "narrow";

/** Словарь надписей. Все поля необязательные: локаль может не содержать
 *  какого-то из вариантов, и это не должно ломать кнопку. */
export interface CtaVariants {
  ctaFull?: string;
  ctaShort?: string;
  ctaTiny?: string;
}

/** Порядок «от самого полного к самому урезанному».
 *  Он же порядок предпочтения при равной длине. */
const ORDER = ["ctaFull", "ctaShort", "ctaTiny"] as const;

/** Сколько первых элементов ORDER доступно на ступени. */
const AVAILABLE: Record<CtaStep, number> = { wide: 1, mid: 2, narrow: 3 };

/** Длина после нормализации: «ā» одним символом и «a» + комбинирующая черта —
 *  это одна и та же надпись, и мерить их надо одинаково. Латышское
 *  «Izmēģināt 30 dienas» в NFD весит 22 символа вместо 19 и без нормализации
 *  проиграло бы на ступени `mid` более длинному варианту.
 *
 *  Нормализация достижима: тест «словарь в NFD» краснеет, если её убрать.
 *  Разбор на кодовые точки (`[...s]`) отсюда снят намеренно — суррогатных пар
 *  в надписях нет, вызывающего у него не было, а механизм, который не может
 *  покраснеть, здесь не живёт.
 *
 *  ⚠️ Цена этого решения: длина считается в единицах UTF-16, и суррогатная
 *  пара весит два. День, когда в надпись кнопки попадёт эмодзи, прокси
 *  переставит варианты молча. Появится эмодзи — вернуть `[...s]` вместе
 *  с тестом, который без него краснеет. */
function width(text: string): number {
  return text.normalize("NFC").length;
}

function usable(dict: CtaVariants, keys: readonly (keyof CtaVariants)[]): string[] {
  return keys.map((k) => dict[k]?.trim() ?? "").filter((s) => s.length > 0);
}

/**
 * Надпись кнопки для данной ступени: самая короткая из доступных на ней.
 *
 * Пустые и отсутствующие варианты выброшены ДО сравнения — иначе пустая
 * строка выигрывала бы соревнование за минимум и кнопка осталась бы без
 * текста. Если на ступени не осталось ни одного варианта, берётся ближайший
 * существующий из остальных (порядок ORDER). Пустая строка возвращается
 * только у словаря, где нет вообще ни одной из трёх надписей.
 *
 * Добавление 13-й локали правки функции не требует: выбор считается из того,
 * что лежит в словаре, а не из таблицы «локаль → вариант».
 */
export function pickCta(dict: CtaVariants, step: CtaStep): string {
  const onStep = usable(dict, ORDER.slice(0, AVAILABLE[step]));
  const candidates = onStep.length > 0 ? onStep : usable(dict, ORDER);
  if (candidates.length === 0) return "";
  return candidates.reduce((best, next) => (width(next) < width(best) ? next : best));
}
